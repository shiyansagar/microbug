function rng(seed) {                              // mulberry32
  let a = seed | 0;
  return () => { a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
}
function hash2(x, y, s) {
  let h = Math.imul(x | 0, 374761393) ^ Math.imul(y | 0, 668265263) ^ Math.imul((s | 0) + 1, 1442695041);
  h = Math.imul(h ^ h >>> 13, 1274126177);
  return ((h ^ h >>> 16) >>> 0) / 4294967296;
}
function vnoise(x, y, s) {
  const xi = Math.floor(x), yi = Math.floor(y), fx = x - xi, fy = y - yi;
  const u = fx * fx * (3 - 2 * fx), v = fy * fy * (3 - 2 * fy);
  return lerp(lerp(hash2(xi, yi, s), hash2(xi + 1, yi, s), u), lerp(hash2(xi, yi + 1, s), hash2(xi + 1, yi + 1, s), u), v);
}
function fbm(x, y, s) { return vnoise(x, y, s) * 0.5 + vnoise(x * 2.03, y * 2.03, s + 7) * 0.3 + vnoise(x * 4.1, y * 4.1, s + 13) * 0.2; }
const pick = (r, a) => a[Math.min(a.length - 1, Math.floor(r() * a.length))];

function fmt(n) {
  n = Math.floor(n);
  if (n < 100000) return n.toLocaleString('en-US');
  if (n < 1e6) return (n / 1000).toFixed(0) + 'k';
  return (n / 1e6).toFixed(2) + 'M';
}
// 1-bit icons for the chrome, drawn as crisp squares
function bmp(rows, scale) {
  const h = rows.length, w = rows[0].length, s = scale || 2; let d = '';
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (rows[y][x] === '#') d += 'M' + x + ' ' + y + 'h1v1h-1z';
  return '<svg class="ico" viewBox="0 0 ' + w + ' ' + h + '" width="' + w * s + '" height="' + h * s + '" shape-rendering="crispEdges" aria-hidden="true"><path d="' + d + '" fill="currentColor"/></svg>';
}
